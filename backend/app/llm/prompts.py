def clean_deepseek_r1_output(raw_text: str) -> str:
    """Strips DeepSeek-R1 chain-of-thought tags (<think>...</think>) and markdown fences.
    
    Guarantees that no internal reasoning process leaks to the user interface.
    """
    # Remove any <think>...</think> sections (including multiline)
    text = re.sub(r"<think>[\s\S]*?</think>", "", raw_text, flags=re.DOTALL)
    
    # Also remove unclosed <think> if response was cut off
    text = re.sub(r"<think>[\s\S]*", "", text, flags=re.DOTALL)
    
    text = text.strip()
    
    # Strip markdown code block wrappers ```json ... ``` or ``` ... ```
    if text.startswith("```"):
        lines = text.split("\n")
        if lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        text = "\n".join(lines).strip()
        
    # Find outer JSON braces if extra prose surrounds it
    first_brace = text.find("{")
    last_brace = text.rfind("}")
    if first_brace != -1 and last_brace != -1 and last_brace > first_brace:
        text = text[first_brace:last_brace + 1]
        
    return text


def build_finding_prompt(req: FindingExplanationRequest) -> str:
    """Builds a strictly structured prompt for explaining a single supervisory finding."""
    payload = {
        "finding_id": req.finding_id,
        "finding_type": req.finding_type,
        "soc_id": req.soc_id,
        "severity": req.severity,
        "confidence": req.confidence,
        "risk_score": req.risk_score,
        "title": req.title,
        "summary": req.summary,
        "baseline": req.baseline,
        "observed": req.observed,
        "missing_actions": req.missing_actions,
        "evidence": req.evidence,
        "recommendation": req.recommendation,
    }
    
    prompt = f"""Explain the following supervisory SOC finding. Follow all system rules strictly.

INPUT STRUCTURED FINDING DATA:
{json.dumps(payload, indent=2)}

You must return a valid JSON object matching this exact schema:
{{
  "title": "<Concise, authoritative title>",
  "summary": "<1-2 sentence high-level executive summary of the breakdown>",
  "what_happened": "<Clear description of what was observed vs expected in the workflow>",
  "why_it_matters": "<Operational security impact: detection blindness, SOP breach, or gaming>",
  "evidence_summary": "<Direct synthesis of the supplied evidence items only>",
  "confidence_statement": "<Statement on why the confidence of {req.confidence * 100:.0f}% is supported by the evidence>",
  "recommended_action": "<Specific remediation based on the provided recommendation>",
  "limitations": ["<Data limitations or investigatory caveats if applicable>"]
}}"""
    return prompt


